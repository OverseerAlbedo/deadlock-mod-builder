//! Building ability objects: the game's object with only its mesh replaced.
//!
//! For every enabled row (only when there are rows; a project without them
//! never reads the object catalog):
//! 1. The target must be offered for the hero (`deadlock_components::ability_objects::allowed`,
//!    the catalog's own rule) and its file prepared and current
//!    (`check_rows`, no Blender).
//! 2. The game's object is decompiled once with the app's Source 2 Viewer CLI
//!    (`compiler::decompile_from_archive`) into a cache keyed by the compiled
//!    file's digest (`original`).
//! 3. The vmdl is the original's text with only the `RenderMeshList` children
//!    replaced by one `RenderMeshFile` (`mesh_vmdl`); every other node stays
//!    byte for byte (for the thrown dagger, its `VSNAPList`). LOD groups, when
//!    an original has them, are pointed at the one new mesh.
//! 4. The mesh is written as an unskinned DMX in the original's axis system
//!    (`deadlock_skeleton::export::export_rigid_bytes`), with the fit applied in
//!    Rust (`deadlock_components::object_fit`).
//! 5. The object's materials are generated by the material pipeline
//!    (`deadlock_materials::generate`) under the object's own folder
//!    (`object_root`): files of the mod, never game files.
//! 6. Materials and model compile only through the model backend selection
//!    (`toolchain::select`), and only with a Community SDK that compiles models
//!    (Reduced CSDK 13 and later); anything else is refused (`NEEDS_CURRENT_SDK`).
//! 7. The compiled model is read back and refused unless its bones,
//!    attachments, hitboxes, physics, animation data, mesh groups and
//!    non-material references equal the original's and its materials are
//!    exactly the generated ones.
//! 8. Only the target and the object's own files are packaged; files the
//!    compiler also writes that the game already has (trail snapshots, the
//!    engine's default textures) are not.
