    #[test]
    fn a_carried_vmdl_keeps_every_node_and_changes_only_the_mesh_files() {
        assert_eq!(mesh_nodes(LEVELS).unwrap().iter().map(|n| n.name.as_str()).collect::<Vec<_>>(), ["body", "outline", "body_lod1", "outline_lod1"]);
        assert_eq!(lod_groups(LEVELS).unwrap(), [vec!["body".to_owned(), "outline".to_owned()], vec!["body_lod1".to_owned(), "outline_lod1".to_owned()]]);
        let root = "models/dmb_objects/sample_12345678";
        let file = |name: &str| Some(format!("{root}/{name}.dmx"));
        // Shells kept: only the four filenames change, byte for byte everything else.
        let kept: BTreeMap<String, Option<String>> = [("body", file("b0")), ("outline", file("s0")), ("body_lod1", file("b1")), ("outline_lod1", file("s1"))].into_iter().map(|(k, v)| (k.to_owned(), v)).collect();
        let out = carried_vmdl(LEVELS, &kept).unwrap();
        let mut back = out.clone();
        for (old, new) in [("models/abilities/sample_body.dmx", "b0"), ("models/abilities/sample_outline.dmx", "s0"), ("models/abilities/sample_body_lod1.dmx", "b1"), ("models/abilities/sample_outline_lod1.dmx", "s1")] {
            back = back.replace(&format!("{root}/{new}.dmx"), old);
        }
        assert_eq!(back, LEVELS);
        // Shells left out: their nodes and their level references go; the rest stays.
        let dropped: BTreeMap<String, Option<String>> = [("body", file("b0")), ("outline", None), ("body_lod1", file("b1")), ("outline_lod1", None)].into_iter().map(|(k, v)| (k.to_owned(), v)).collect();
        let out = carried_vmdl(LEVELS, &dropped).unwrap();
        assert_eq!(mesh_nodes(&out).unwrap().iter().map(|n| (n.name.as_str(), n.filename.as_str())).collect::<Vec<_>>(), [("body", format!("{root}/b0.dmx").as_str()), ("body_lod1", format!("{root}/b1.dmx").as_str())]);
        assert_eq!(lod_groups(&out).unwrap(), [vec!["body".to_owned()], vec!["body_lod1".to_owned()]]);
        let doc = Document::parse(&out).unwrap();
        for class in ["Skeleton", "Bone", "AttachmentList", "PhysicsShapeCapsule"] {
            assert_eq!(doc.objects(Some(class)).len(), 1, "{class} kept");
        }
        assert!(out.contains("switch_threshold = 10.0"));
        // A node the build has no file for is refused; a hull file goes through the compiler
        // (the app's switches keep the game's own collision, `refused_nodes`).
        assert!(carried_vmdl(LEVELS, &BTreeMap::from([("body".to_owned(), file("b0"))])).is_err());
        assert!(carried_vmdl(&LEVELS.replace("PhysicsShapeCapsule", "PhysicsHullFile"), &kept).is_ok());
    }

    /// A unit cube of six quads, winding outwards, one normal per corner (flat faces).
    fn cube(material: &str) -> PreparedMesh {
        let positions: Vec<[f64; 3]> = (0..8).map(|k| [f64::from(k & 1), f64::from((k >> 1) & 1), f64::from((k >> 2) & 1)].map(|v| v - 0.5)).collect();
        let quads: [([usize; 4], [f64; 3]); 6] = [([0, 2, 3, 1], [0., 0., -1.]), ([4, 5, 7, 6], [0., 0., 1.]), ([0, 1, 5, 4], [0., -1., 0.]), ([2, 6, 7, 3], [0., 1., 0.]), ([0, 4, 6, 2], [-1., 0., 0.]), ([1, 3, 7, 5], [1., 0., 0.])];
        let mut normals = vec![];
        let mut faces = vec![];
        for (quad, normal) in quads {
            let start = normals.len();
            normals.extend([normal; 4]);
            faces.push(deadlock_skeleton::export::PreparedFace { vertices: quad.to_vec(), corners: (start..start + 4).collect(), material: material.into() });
        }
        PreparedMesh { name: "cube".into(), positions, normals, uvs: vec![], colors: vec![], tangents: vec![], weights: vec![], faces, extra: BTreeMap::new() }
    }

    #[test]
    fn the_lighter_preview_copy_is_bound_like_its_meshes() {
        use deadlock_components::object_follow::Binding;
        use deadlock_project::ability_objects::FollowWay;
        let part = |name: &str, x: f64| PreparedMesh { extra: BTreeMap::from([("part".to_owned(), serde_json::json!(name))]), positions: cube("m").positions.iter().map(|p| [p[0] + x, p[1], p[2]]).collect(), ..cube("m") };
        let packet = Packet { version: "v".into(), unit_metres: 1., meshes: vec![part("column", 0.), part("bar", 5.)], materials: BTreeMap::new(), warnings: vec![], preview: vec![], armature: vec![] };
        // The lighter copy: fewer points, in the same order as the meshes.
        let light = |m: &PreparedMesh| PreparedMesh { positions: m.positions[..4].iter().map(|p| [p[0], p[1], p[2] + 0.01]).collect(), ..m.clone() };
        let preview: Vec<PreparedMesh> = packet.meshes.iter().map(light).collect();
        let by_parts = Binding { way: FollowWay::ByParts, parts: BTreeMap::from([("column".into(), "main".into()), ("bar".into(), "full_bottom".into())]), suggested: BTreeMap::new() };
        let full: Vec<PreparedMesh> = packet.meshes.iter().map(|m| PreparedMesh { weights: vec![vec![("x".into(), 1.)]; 8], ..m.clone() }).collect();
        let bound = bound_preview(&packet, &by_parts, &full, &preview).unwrap();
        assert_eq!(bound[0].weights, vec![vec![("main".to_owned(), 1.)]; 4]);
        assert_eq!(bound[1].weights, vec![vec![("full_bottom".to_owned(), 1.)]; 4]);
        assert_eq!(bound[1].positions, preview[1].positions);
        // The file's own weights: each light point takes its nearest full point's.
        let own = Binding { way: FollowWay::SameSkeleton, parts: BTreeMap::new(), suggested: BTreeMap::new() };
        let weighted: Vec<PreparedMesh> = packet.meshes.iter().map(|m| PreparedMesh { weights: (0..8).map(|i| vec![(format!("b{i}"), 1.)]).collect(), ..m.clone() }).collect();
        let bound = bound_preview(&packet, &own, &weighted, &preview).unwrap();
        assert_eq!(bound[0].weights, (0..4).map(|i| vec![(format!("b{i}"), 1.)]).collect::<Vec<_>>());
        // A copy that does not pair mesh for mesh is not bound.
        assert!(bound_preview(&packet, &by_parts, &full, &preview[..1]).is_none());
    }

    #[test]
    fn the_outline_shell_is_pushed_out_along_the_mean_normals_and_turned_like_the_games() {
        let body = cube("models/dmb_objects/x/a.vmat");
        let style = ShellStyle { distance: 0.5, turned: true, normals_turned: false };
        let shell = &shell_meshes(std::slice::from_ref(&body), &style, "models/base/glow.vmat")[0];
        // A corner moves along the mean of its three face normals: (1, 1, 1) / √3 times 0.5.
        let d = 0.5 / 3f64.sqrt();
        for (p, q) in body.positions.iter().zip(&shell.positions) {
            for k in 0..3 {
                assert!((q[k] - (p[k] + p[k].signum() * d)).abs() < 1e-12, "{p:?} → {q:?}");
            }
        }
        assert!(shell.faces.iter().all(|f| f.material == "models/base/glow.vmat"));
        assert_eq!(shell.faces[0].vertices, [1, 3, 2, 0], "turned");
        // The game's own style is read from its DMX files: a body and its inside-out shell.
        let game_body = deadlock_dmx::Dmx::parse(export_rigid_bytes(&[body.clone()], None).unwrap()).unwrap();
        let inside_out = shell_meshes(&[body.clone()], &ShellStyle { distance: 0.6, turned: true, normals_turned: false }, "m.vmat");
        let game_shell = deadlock_dmx::Dmx::parse(export_rigid_bytes(&inside_out, None).unwrap()).unwrap();
        assert_eq!(shell_style(&game_body, &game_shell, 0.6).unwrap(), ShellStyle { distance: 0.6, turned: true, normals_turned: false });
        assert_eq!(shell_style(&game_body, &game_body, 0.6).unwrap(), ShellStyle { distance: 0.6, turned: false, normals_turned: false });
        assert_eq!(dmx_materials(&game_shell), BTreeSet::from(["m.vmat".to_owned()]));
        // Bound to one bone, every point wholly.
        let skeleton = deadlock_skeleton::Skeleton { names: vec!["joint1".into()], parents: vec![-1], positions: vec![[0.; 3]], rotations: vec![[0., 0., 0., 1.]], scales: vec![1.], flags: vec![] };
        let raw = body_dmx(&[body], Some(&skeleton), Some((3, 1, 0))).unwrap();
        let dmx = deadlock_dmx::Dmx::parse(raw).unwrap();
        assert_eq!(dmx.elements.iter().filter(|e| e.kind == "DmeJoint").map(|e| e.name.as_str()).collect::<Vec<_>>(), ["joint1"]);
        assert_eq!(axis_system(&dmx), Some((3, 1, 0)));
    }

